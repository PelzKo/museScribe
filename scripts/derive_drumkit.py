"""Derive the drum legend of every show from its truth scores -> drumkit.yaml (repo root).

    python scripts/derive_drumkit.py [show ...]       # default: every show in data/

No show prints a legend page, so the legend is learned from the hand-corrected drum parts (every
<unpitched> note: staff position, notehead, kit instrument, MIDI). Re-run it whenever a new drum truth
is linked (IMPROVEMENTS #29); the pipeline maps drum notes through it. Hand notes per show go under
`notes:` in drumkit.yaml and are kept.
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from omrbench import project, truth  # noqa: E402

OUT = REPO / "drumkit.yaml"


def kit_of(part) -> Counter:
    """(position, notehead, instrument, midi) of every unpitched note of a truth <part>."""
    root = part.getroottree().getroot()
    sp = next(s for s in root.iterfind("part-list/score-part") if s.get("id") == part.get("id"))
    names = {i.get("id"): (i.findtext("instrument-name") or "").strip() for i in sp.iterfind("score-instrument")}
    midi = {m.get("id"): int(m.findtext("midi-unpitched") or 0) for m in sp.iterfind("midi-instrument")}
    out: Counter = Counter()
    for n in part.iter("note"):
        u = n.find("unpitched")
        if u is None:
            continue
        pos = f"{u.findtext('display-step', '?').strip()}{u.findtext('display-octave', '?').strip()}"
        iid = n.find("instrument").get("id") if n.find("instrument") is not None else None
        out[(pos, (n.findtext("notehead") or "normal").strip(), names.get(iid, ""), midi.get(iid, 0))] += 1
    return out


def _legend(kit: Counter) -> dict:
    positions: dict = {}
    for (pos, head, inst, m), n in kit.most_common():
        e = {"notehead": head, "instrument": inst, "midi": m, "count": n}
        if pos not in positions:
            positions[pos] = e
        else:
            positions[pos].setdefault("also", []).append(e)
    return dict(sorted(positions.items()))


def derive(show: str) -> dict:
    """{truth part name: {from: [song ids], positions: {pos: {notehead, instrument, midi, count}}}}."""
    from lxml import etree
    proj = project.load(REPO / "data" / show)
    kits: dict[str, Counter] = {}
    songs: dict[str, list] = {}
    for song in proj.songs.values():
        if not song.truth or not song.truth.exists():
            continue
        root = etree.parse(str(truth.convert(song.truth, REPO / "results" / "cache", None))).getroot()
        skip = {" ".join(u.lower().split()) for u in song.unfinished}
        for name, part in truth.parts(root):
            if " ".join(name.lower().split()) in skip:
                continue
            c = kit_of(part)
            if c:
                kits[name] = kits.get(name, Counter()) + c
                songs.setdefault(name, []).append(song.id)
    return {name: {"from": songs[name], "positions": _legend(k)} for name, k in kits.items()}


def main(shows: list[str]) -> None:
    old = yaml.safe_load(OUT.read_text()) if OUT.exists() else {}
    shows = shows or [p.name for p in project.projects(REPO / "data")]
    out = dict(old or {})
    for show in shows:
        kits = derive(show)
        if kits:
            out[show] = {"kits": kits, "notes": (old.get(show) or {}).get("notes", [])}
        for name, k in kits.items():
            print(f"{show} / {name}: {len(k['positions'])} positions from songs {k['from']}")
    OUT.write_text("# generated by scripts/derive_drumkit.py from the truth drum parts; edit only `notes:`\n"
                   + yaml.safe_dump(out, sort_keys=False, allow_unicode=True))


if __name__ == "__main__":
    main(sys.argv[1:])
